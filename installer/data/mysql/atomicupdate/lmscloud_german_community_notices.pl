                    "LiebeR [%- INCLUDE 'patron-title.inc' patron => owner -%] <br>,",
                    "<br>",
                    "Eine öffentliche Liste mit dem Titel <em>[% shelf.shelfname | html %]</em> wurde von [% IF ( librarian ) %][%- INCLUDE 'patron-title.inc' patron => librarian %].[% END %] an Sie<br> übertragen",
                    "<br>",
                    "[% IF old_owner %]Die Liste war zuvor im Besitz von [%- INCLUDE 'patron-title.inc' patron => old_owner -%].<br><br>[% END %]",
                    "Danke<br>",
                    "<br>",
                ),
            },
        );

        for my $notice (@inserts) {
            my $added = $dbh->do(
                q{
                INSERT IGNORE INTO letter
                    (module, code, branchcode, name, is_html, title, content, message_transport_type, lang)
                VALUES (?, ?, '', ?, ?, ?, ?, ?, 'default')
            }, undef,
                @{$notice}{qw(module code name is_html title content message_transport_type)}
            );

            # DBI returns the truthy string "0E0" for zero affected rows, so compare numerically
            if ( $added > 0 ) {
                say_success( $out, "Added the $notice->{code} notice" );
            } else {
                say_info( $out, "$notice->{code} notice already present, skipping" );
            }
        }

        # The notices list groups by name, so rows of one notice with different
        # names per transport show up as separate notices. Name every transport
        # after the email row, as saving the notice in the editor would.
        my $renamed = $dbh->do(
            q{
            UPDATE letter l
            JOIN letter e
              ON  e.module = l.module AND e.code = l.code
              AND e.branchcode = l.branchcode AND e.lang = l.lang
              AND e.message_transport_type = 'email'
            SET l.name = e.name, l.updated_on = l.updated_on
            WHERE l.message_transport_type <> 'email'
              AND l.name <> e.name
        }
        );
        say_success( $out, "Aligned the names of $renamed notice transport(s)" ) if $renamed > 0;
    },
};
